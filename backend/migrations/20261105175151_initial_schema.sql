-- Global
CREATE TABLE types
(
    id   int PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
);

CREATE TABLE entities
(
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       int         NOT NULL REFERENCES types (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    version    int         NOT NULL DEFAULT 1
);

-- Aufgaben
CREATE TABLE task_groups
(
    id   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
);

CREATE TABLE task_states
(
    id           int PRIMARY KEY,
    name         varchar(50) NOT NULL UNIQUE
);

CREATE TABLE task_priorities
(
    id           int PRIMARY KEY,
    name         varchar(50) NOT NULL UNIQUE
);

CREATE TABLE tasks
(
    entity_id    int PRIMARY KEY REFERENCES entities (id),
    group_id     int          NOT NULL REFERENCES task_groups (id),

    name         varchar(150) NOT NULL,
    description  text,

    state_id     int          NOT NULL REFERENCES task_states (id),
    priority_id  int          NOT NULL REFERENCES task_priorities (id),

    due_at       timestamptz,
    completed_at timestamptz
);


-- Kalender
CREATE TABLE calendar_entries
(
    entity_id        int PRIMARY KEY REFERENCES entities (id),
    source_entity_id int REFERENCES entities (id),

    is_reminder      boolean     NOT NULL DEFAULT false,

    planned_start_at timestamptz NOT NULL,
    planned_end_at   timestamptz,
    actual_start_at  timestamptz,
    actual_end_at    timestamptz,

    CONSTRAINT valid_planned_time CHECK (
        (is_reminder AND planned_end_at IS NULL)
            OR
        (NOT is_reminder AND planned_end_at IS NOT NULL
            AND planned_end_at > planned_start_at)
        ),

    CONSTRAINT valid_actual_time CHECK (
        actual_end_at IS NULL
            OR
        (actual_start_at IS NOT NULL
            AND actual_end_at >= actual_start_at)
        )
);