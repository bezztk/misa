CREATE TABLE flashcards
(
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_node_id     integer REFERENCES domain_nodes (id) NOT NULL,

    front              text                                 NOT NULL,
    back               text                                 NOT NULL,
    hint               text,
    explanation        text,

    state              smallint                             NOT NULL DEFAULT 0,
    learning_step      smallint                             NOT NULL DEFAULT 0,

    retention_class_id integer
        REFERENCES flashcard_retention_classes (id)         NOT NULL,

    stability          real,
    difficulty         real,

    last_reviewed_at   timestamptz,
    due_at             timestamptz
);

CREATE TABLE flashcard_reviews
(
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flashcard_id integer     NOT NULL REFERENCES flashcards (id),

    rating       smallint    NOT NULL, -- Again, Hard, Good, Easy
