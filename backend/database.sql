CREATE TABLE domain_nodes
(
    id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id              integer REFERENCES domains (id) NOT NULL,
    parent_id              integer REFERENCES domain_nodes (id),

    name                   varchar(150)                    NOT NULL,
    is_system_value        bool                            NOT NULL,
    last_verified_at       timestamptz,

    cognitive_level_id     integer REFERENCES cognitive_levels (id),

    -- Skill Extension
    has_skill              bool DEFAULT FALSE              NOT NULL,
    psychomotor_level_id   integer REFERENCES psychomotor_levels (id),

    -- Document Extension
    has_document           bool DEFAULT FALSE              NOT NULL,
    content                text                            NOT NULL DEFAULT '',
    completeness_level_id  integer REFERENCES document_completeness_levels (id),
    flashcard_status_id    integer REFERENCES document_flashcard_statuses (id),
    verification_status_id integer REFERENCES document_verification_statuses (id),
    verification_level_id  integer REFERENCES document_verification_levels (id),

    CHECK (id <> parent_id),
    UNIQUE(parent_id, name)
);

