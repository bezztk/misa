use crate::api::handlers::{
    attachment_handler, calendar_entry_handler, comment_handler, document_handler, domain_handler,
    entity_handler, flashcard_handler, idea_handler, media_handler, metadata_handler,
    progression_handler, pursuit_handler, routine_handler, rss_handler, source_handler,
    task_handler,
};
use axum::{Router, routing::get};
use sqlx::PgPool;

pub fn create_router(pool: PgPool) -> Router {
    let api_routes = Router::new()
        .route(
            "/sources",
            get(source_handler::get_sources).post(source_handler::create_source),
        )
        .route(
            "/sources/{id}",
            axum::routing::delete(source_handler::delete_source),
        )
        .route(
            "/sources/{id}/title",
            axum::routing::patch(source_handler::update_title),
        )
        .route(
            "/sources/{id}/category",
            axum::routing::put(source_handler::assign_category),
        )
        .route(
            "/source-categories",
            get(source_handler::get_categories).post(source_handler::create_category),
        )
        .route(
            "/source-categories/{id}",
            axum::routing::put(source_handler::rename_category)
                .delete(source_handler::delete_category),
        )
        .route("/media", get(media_handler::get_all))
        .route(
            "/media/import",
            axum::routing::post(media_handler::import_media),
        )
        .route(
            "/media/{id}",
            get(media_handler::get_media)
                .patch(media_handler::update_media)
                .delete(media_handler::delete_media),
        )
        .route(
            "/media/{id}/sync",
            axum::routing::post(media_handler::sync_media),
        )
        .route("/media/{id}/seasons", get(media_handler::get_seasons))
        .route(
            "/media/{id}/progress",
            get(media_handler::get_series_progress),
        )
        .route(
            "/media/{id}/seasons/{season_id}/episodes",
            get(media_handler::get_episodes),
        )
        .route(
            "/media/{id}/seasons/{season_id}/progress",
            get(media_handler::get_season_progress),
        )
        .route(
            "/media/{id}/seasons/{season_id}/episodes/{episode_id}",
            axum::routing::patch(media_handler::update_episode_watched),
        )
        .route(
            "/rss/feeds",
            get(rss_handler::get_feeds).post(rss_handler::create_feed),
        )
        .route(
            "/rss/feeds/{id}",
            axum::routing::patch(rss_handler::update_feed).delete(rss_handler::delete_feed),
        )
        .route(
            "/rss/feeds/refresh",
            axum::routing::post(rss_handler::refresh_all_feeds),
        )
        .route(
            "/rss/feeds/{id}/refresh",
            axum::routing::post(rss_handler::refresh_feed),
        )
        .route(
            "/rss/feeds/{id}/category",
            axum::routing::put(rss_handler::assign_feed_category),
        )
        .route(
            "/rss/feeds/{id}/read",
            axum::routing::post(rss_handler::mark_feed_read),
        )
        .route(
            "/rss/categories",
            get(rss_handler::get_categories).post(rss_handler::create_category),
        )
        .route(
            "/rss/categories/{id}",
            axum::routing::put(rss_handler::update_category).delete(rss_handler::delete_category),
        )
        .route("/rss/entries", get(rss_handler::get_entries))
        .route(
            "/rss/entries/{id}",
            axum::routing::patch(rss_handler::update_entry),
        )
        .route(
            "/routines/generate-executions",
            axum::routing::post(routine_handler::generate_executions),
        )
        .route(
            "/calendar-entries",
            get(calendar_entry_handler::get_calendar_entries)
                .post(calendar_entry_handler::create_calendar_entry),
        )
        .route(
            "/calendar-entries/{id}",
            axum::routing::patch(calendar_entry_handler::update_calendar_entry)
                .delete(calendar_entry_handler::delete_calendar_entry),
        )
        .route(
            "/ideas",
            get(idea_handler::get_ideas).post(idea_handler::create_idea),
        )
        .route(
            "/ideas/{id}",
            axum::routing::delete(idea_handler::delete_idea),
        )
        .route(
            "/ideas/{id}/fields/{field_id}",
            axum::routing::patch(idea_handler::update_idea_field),
        )
        .route(
            "/entities/{entity_id}/comments",
            axum::routing::post(comment_handler::create_comment),
        )
        .route(
            "/entities/{entity_id}/versions",
            get(entity_handler::get_field_versions),
        )
        .route(
            "/comments/{id}",
            axum::routing::patch(comment_handler::update_comment)
                .delete(comment_handler::delete_comment),
        )
        .route("/domain-tree", get(domain_handler::get_domain_tree))
        .route(
            "/domains/{id}",
            axum::routing::patch(domain_handler::update_domain),
        )
        .route(
            "/domain-nodes/{parent_id}/children",
            axum::routing::post(domain_handler::create_domain_node),
        )
        .route(
            "/domains/{domain_id}/nodes",
            axum::routing::post(domain_handler::create_root_domain_node),
        )
        .route(
            "/domain-nodes/{id}",
            axum::routing::delete(domain_handler::delete_domain_node),
        )
        .route(
            "/domain-nodes/{id}/fields/{field_id}",
            axum::routing::patch(domain_handler::update_domain_node_field),
        )
        .route(
            "/domain-nodes/{node_id}/document",
            get(document_handler::get_document)
                .post(document_handler::create_document)
                .put(document_handler::update_document)
                .delete(document_handler::delete_document),
        )
        .route(
            "/domain-nodes/{node_id}/document/versions",
            get(document_handler::get_document_versions),
        )
        .route(
            "/domain-nodes/{node_id}/document/versions/{version}/restore",
            axum::routing::post(document_handler::restore_document_version),
        )
        .route(
            "/flashcards/due",
            get(flashcard_handler::get_due_flashcards),
        )
        .route(
            "/flashcards/{id}",
            axum::routing::delete(flashcard_handler::delete_flashcard),
        )
        .route(
            "/flashcards/{id}/fields/{field_id}",
            axum::routing::patch(flashcard_handler::update_flashcard_field),
        )
        .route(
            "/flashcards/{id}/reviews",
            axum::routing::post(flashcard_handler::review_flashcard),
        )
        .route(
            "/domain-nodes/{node_id}/flashcards",
            get(flashcard_handler::get_flashcards).post(flashcard_handler::create_flashcard),
        )
        .route(
            "/domain-nodes/{node_id}/attachments",
            get(attachment_handler::get_attachments).post(attachment_handler::create_attachment),
        )
        .route(
            "/attachments/{id}",
            axum::routing::delete(attachment_handler::delete_attachment),
        )
        .route(
            "/domain-nodes/{node_id}/pursuits",
            get(pursuit_handler::get_pursuits).post(pursuit_handler::create_pursuit),
        )
        .route(
            "/pursuits/{id}/requirements",
            axum::routing::put(pursuit_handler::update_requirements),
        )
        .route(
            "/progressions",
            get(progression_handler::get_progressions)
                .post(progression_handler::create_progression),
        )
        .route(
            "/progressions/{id}/fields/{field_id}",
            axum::routing::patch(progression_handler::update_progression_field),
        )
        .route(
            "/progressions/{id}/stages",
            axum::routing::post(progression_handler::create_stage),
        )
        .route(
            "/pursuits/available",
            get(progression_handler::get_available_pursuits),
        )
        .route(
            "/progression-stages/{id}/pursuits",
            axum::routing::post(progression_handler::assign_pursuit),
        )
        .route("/metadata", get(metadata_handler::get_metadata))
        .route(
            "/tasks/{id}",
            axum::routing::delete(task_handler::delete_task),
        )
        .route(
            "/tasks/{id}/fields/{field_id}",
            axum::routing::patch(task_handler::update_task_field),
        )
        .route(
            "/tasks",
            get(task_handler::get_tasks).post(task_handler::create_task),
        );

    Router::new()
        .route("/health", get(health))
        .nest("/api", api_routes)
        .with_state(pool)
}

async fn health() -> &'static str {
    "OK"
}
